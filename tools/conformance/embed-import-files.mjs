// 把 fixtures/import/ 下的原始账单文件**逐字节**内嵌成 ArkTS 模块。
//
// 与 embed-fixtures.mjs 的分工：
//   embed-fixtures.mjs  内嵌 **fixture JSON**（期望值 + input 描述）
//   本脚本            内嵌 **被解析的原始文件**（CSV / OFX / QFX 字节）
// 两者都是"主机执行面拿不到 fs"的产物（实测 fs.readTextSync → is not callable）。
//
// 为什么用 Base64 而不是直接内嵌文本：
//   这批文件不是纯文本 —— 其中 `csv-gb18030.csv` / `gbk.csv` **不是合法 UTF-8**
//   （实测：22 个文件里这两个 python .decode('utf-8') 抛错）。
//   若在 Node 侧先 decode 再内嵌字符串，等于把"字节 → 文本"这一步偷偷挪出被测代码，
//   那么 GB18030 相关用例的正确性就永远测不到，且这种偷换不会被任何 Gate 发现。
//   因此这里内嵌 **字节**（Base64），解码仍由被测代码在运行时完成。
//
// 用法：
//   node tools/conformance/embed-import-files.mjs           # 生成
//   node tools/conformance/embed-import-files.mjs --check   # 校验未漂移
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from 'node:fs'
import { join, dirname, posix } from 'node:path'

const REPO = process.cwd()
const SRC_DIR = join(REPO, 'fixtures', 'import')
const OUT = join(REPO, 'harmony', 'entry', 'src', 'test', 'fixtures', 'ImportBundle.ets')
const CHECK = process.argv.includes('--check')

if (!existsSync(SRC_DIR)) {
  console.error('[embed-import-files] missing:', SRC_DIR)
  process.exit(1)
}

// 按文件名排序 —— 生成必须确定性，否则 --check 会因为遍历顺序而假失败。
const names = readdirSync(SRC_DIR).filter((f) => f.endsWith('.csv') || f.endsWith('.ofx') || f.endsWith('.qfx')).sort()
if (names.length === 0) {
  console.error('[embed-import-files] no import files found')
  process.exit(1)
}

const rows = names.map((n) => ({
  name: `fixtures/import/${n}`,
  b64: readFileSync(join(SRC_DIR, n)).toString('base64'),
}))

const lines = []
lines.push('// DO NOT EDIT — generated by tools/conformance/embed-import-files.mjs')
lines.push('// 原始文件 fixtures/import/* 的**字节**（Base64 内嵌），供主机执行面使用。')
lines.push('//')

lines.push('export const IMPORT_FILE_NAMES: string[] = [')
rows.forEach((r) => lines.push(`  ${JSON.stringify(r.name)},`))
lines.push('];')
lines.push('')
lines.push('export const IMPORT_FILE_BASE64: string[] = [')
rows.forEach((r) => lines.push(`  ${JSON.stringify(r.b64)},`))
lines.push('];')
lines.push('')
const content = lines.join('\n')

if (CHECK) {
  if (!existsSync(OUT)) {
    console.error('[embed-import-files] missing generated file:', OUT)
    process.exit(1)
  }
  const existing = readFileSync(OUT, 'utf8')
  if (existing !== content) {
    console.error('[embed-import-files] embedded import files are out of date or hand-edited')
    process.exit(1)
  }
  console.log(`[embed-import-files] ok (${rows.length} file(s))`)
  process.exit(0)
}

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, content, 'utf8')
console.log(`[embed-import-files] wrote ${rows.length} file(s) -> ${posix.join('harmony/entry/src/test/fixtures/ImportBundle.ets')}`)
